#!/usr/bin/env python3
"""Generate spec/register-map.yaml from spec/network-interface.md (B8, Tables B8-2 and B8-3).

The markdown tables in B8 are the normative source; the YAML is a machine-readable copy for
the reference model (0019), the test bench and tools/spec_lint.py (check L7).

Run from product/spec:  python3 tools/regmap.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "network-interface.md"
OUT = ROOT / "spec" / "register-map.yaml"


def table_after(lines, title):
    start = next(i for i, l in enumerate(lines) if l.startswith(title))
    rows, seen = [], False
    for l in lines[start + 1:]:
        if l.startswith("|"):
            seen = True
            rows.append([c.strip() for c in l.strip().strip("|").split("|")])
        elif seen:
            break
    return rows[2:]  # skip header and separator


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    lines = SPEC.read_text().splitlines()
    regs = table_after(lines, "Table B8-2")
    codes = table_after(lines, "Table B8-3")
    text = SPEC.read_text()
    consts = re.findall(r"Constant `([A-Z][A-Z0-9_]+)` = (0x[0-9A-Fa-f]+)", text)

    out = ["# Generated by tools/regmap.py from spec/network-interface.md B8 — do not edit by hand.",
           "# Normative source: Tables B8-2 and B8-3. (c) 2026 ON8ST, CC BY 4.0.",
           "registers:"]
    n = 0
    for name, addr, access, content, sent, source in (r[:6] for r in regs if len(r) >= 6):
        m = re.match(r"`([A-Z][A-Z0-9_]+)`", name)
        label = m.group(1) if m else name
        a = re.findall(r"0x[0-9A-Fa-f]{4}", addr)
        out += [f"  - name: {label}" if m else f"  - name: {q(label)}",
                f"    address: {a[0]}" if a else "    address: null"]
        if len(a) > 1:
            out.append(f"    address_end: {a[1]}")
        out += [f"    access: {q(access)}", f"    content: {q(content)}",
                f"    sent: {q(sent)}", f"    source: {q(source)}"]
        n += 1
    out.append("codes:")
    ncode = 0
    for row in codes:
        if len(row) < 2:
            continue
        out.append(f"  - set: {q(row[0])}")
        out.append("    values:")
        for num, sym in re.findall(r"(\d+) `([A-Z][A-Z0-9_]+)`", row[1]):
            out.append(f"      - name: {sym}")
            out.append(f"        value: {num}")
            ncode += 1
    # write-reject reasons (B8.4)
    out.append("write_status:")
    m = re.search(r"\[7:0\] the reason:(.*?)\.\s", text, re.S)
    for num, sym in re.findall(r"(\d+) `([A-Z][A-Z0-9_]+)`", m.group(1) if m else ""):
        out += [f"  - name: {sym}", f"    value: {num}"]
    # management commands (Table A1-2)
    out.append("management_commands:")
    for row in table_after(lines, "Table A1-2"):
        names = re.findall(r"`([A-Z][A-Z0-9_]+)`", row[1]) if len(row) > 1 else []
        for nm in names:
            out += [f"  - name: {nm}", f"    code: {q(row[0])}", f"    auth: {q(row[2])}"]
    # TCI names used by part C (commands and G7250_ extensions)
    tci = sorted(set(re.findall(r"`([A-Z][A-Z0-9_]+)`", (ROOT / "spec" / "part-c-tci-profile.md").read_text())))
    out.append("tci_names:")
    out += [f"  - name: {t}" for t in tci]
    consts += re.findall(r"`(CAP_BASE)` = (0x[0-9A-Fa-f]+)", text)
    out.append("constants:")
    for name, val in consts:
        out += [f"  - name: {name}", f"    value: {val}"]
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {n} registers, {ncode} codes, {len(consts)} constants")
    return 0


if __name__ == "__main__":
    sys.exit(main())
