#!/usr/bin/env python3
"""Generate spec/register-map.yaml from the normative tables of the spec.

Sources (normative):
  spec/network-interface.md  Table B8-2 (registers), Table B8-3 (all codes and symbols,
                             authoritative per 0022 §19), Table A1-2 (management commands),
                             constants stated as "Constant `NAME` = 0x..." or "`CAP_BASE` = 0x...".
  spec/part-c-tci-profile.md command tables (rows that start with a back-quoted name).

The YAML is a machine-readable copy for the reference model (0019), the test bench and
tools/spec_lint.py (check L7). Do not edit the YAML by hand.

Run from product/spec:  python3 tools/regmap.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "network-interface.md"
PARTC = ROOT / "spec" / "part-c-tci-profile.md"
OUT = ROOT / "spec" / "register-map.yaml"
SYM = r"[A-Z][A-Z0-9_]*"


def table_after(lines, title):
    start = next(i for i, l in enumerate(lines) if l.startswith(title))
    rows, seen = [], False
    for l in lines[start + 1:]:
        if l.startswith("|"):
            seen = True
            rows.append([c.strip() for c in l.strip().strip("|").split("|")])
        elif seen:
            break
    return rows[2:]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse_codes(cell):
    """'0 none; 2 `SWR_REPEATED` (text), class 1; ...' -> [(value, symbol|None, text, class|None)]"""
    out = []
    for part in re.split(r";\s*", cell):
        m = re.match(r"(0x[0-9A-Fa-f]+|\d+)\s*(?:`(%s)`)?\s*(.*)" % SYM, part.strip())
        if not m:
            continue
        val, sym, rest = m.group(1), m.group(2), m.group(3).strip()
        cls = re.search(r"class (\d)", rest)
        out.append((val, sym, rest, cls.group(1) if cls else None))
    return out


def expand_codes(codecell, names):
    """'0x0020, 0x0021' or '0x0040–0x0046' paired with a list of names."""
    rng = re.match(r"(0x[0-9A-Fa-f]+)\s*[–-]\s*(0x[0-9A-Fa-f]+)", codecell)
    if rng:
        lo, hi = int(rng.group(1), 16), int(rng.group(2), 16)
        codes = [f"0x{v:04X}" for v in range(lo, hi + 1)]
    else:
        codes = re.findall(r"0x[0-9A-Fa-f]+", codecell)
    if len(codes) != len(names):
        return [(n, codecell) for n in names]
    return list(zip(names, codes))


def main():
    text = SPEC.read_text()
    lines = text.splitlines()
    out = ["# Generated by tools/regmap.py from the spec tables — do not edit by hand.",
           "# Normative sources: network-interface.md Tables B8-2, B8-3, A1-2; part C command tables.",
           "# (c) 2026 ON8ST, CC BY 4.0.", "registers:"]
    nreg = 0
    for r in table_after(lines, "Table B8-2"):
        if len(r) < 6:
            continue
        name, addr, access, content, sent, source = r[:6]
        m = re.match(r"`(%s)`" % SYM, name)
        a = re.findall(r"0x[0-9A-Fa-f]{4}", addr)
        out.append(f"  - name: {m.group(1)}" if m else f"  - name: {q(name)}")
        out.append(f"    address: {a[0]}" if a else "    address: null")
        if len(a) > 1:
            out.append(f"    address_end: {a[1]}")
        out += [f"    access: {q(access)}", f"    content: {q(content)}",
                f"    sent: {q(sent)}", f"    source: {q(source)}"]
        nreg += 1

    out.append("code_sets:")
    ncode = 0
    for r in table_after(lines, "Table B8-3"):
        if len(r) < 2:
            continue
        out += [f"  - set: {q(r[0])}", "    values:"]
        seen = set()
        for val, sym, rest, cls in parse_codes(r[1]):
            if not sym and (val in seen or re.match(r"(and|or|are|is|to|of)\b", rest)):
                continue  # prose fragment such as "13 and 14 are never set over P2"
            seen.add(val)
            out.append(f"      - value: {val}")
            if sym:
                out.append(f"        name: {sym}")
            if rest:
                out.append(f"        text: {q(rest)}")
            if cls:
                out.append(f"        class: {cls}")
            ncode += 1

    out.append("management_commands:")
    ncmd = 0
    for r in table_after(lines, "Table A1-2"):
        if len(r) < 3:
            continue
        names = re.findall(r"`(%s)`" % SYM, r[1])
        for nm, code in expand_codes(r[0], names):
            out += [f"  - name: {nm}", f"    code: {q(code)}", f"    auth: {q(r[2])}"]
            ncmd += 1

    tci, header = [], ""
    ptext = PARTC.read_text()
    for l in ptext.splitlines():
        if l.startswith("|") and not re.match(r"\|\s*`", l) and not set(l) <= set("|-: "):
            header = l.lower()          # remember the header row of the current table
        elif not l.startswith("|"):
            header = ""
        if re.match(r"\|\s*`(%s)`" % SYM, l) and "modulation" not in header and "mode " not in header:
            tci += re.findall(r"`(%s)`" % SYM, l.split("|")[1])
    ext = sorted(set(re.findall(r"`(G7250_[A-Z0-9_]+)", ptext)) - {"G7250_"})
    tci = sorted(set(tci) - set(ext) - {"G7250_"})
    out.append("tci_commands:")
    out += [f"  - name: {t}" for t in tci]
    out.append("tci_extensions:")
    out += [f"  - name: {t}" for t in ext]

    consts = dict(re.findall(r"Constant `(%s)` = (0x[0-9A-Fa-f]+)" % SYM, text))
    consts.update(re.findall(r"`(CAP_BASE)` = (0x[0-9A-Fa-f]+)", text)[:1])
    out.append("constants:")
    for name, val in consts.items():
        out += [f"  - name: {name}", f"    value: {val}"]

    new_text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text() == new_text else 1
    OUT.write_text(new_text)
    print(f"{OUT.relative_to(ROOT)}: {nreg} registers, {ncode} codes, {ncmd} management commands, "
          f"{len(tci)} TCI commands, {len(ext)} G7250 extensions, {len(consts)} constants")
    return 0


if __name__ == "__main__":
    sys.exit(main())
