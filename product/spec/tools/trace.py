#!/usr/bin/env python3
"""Traceability helper for the G7250-P2 spec (rc1 check 3).

For every decision in decisions/, lists the spec sections (nearest heading) that cite it, and
the number of Consequences bullets in the decision. Writes spec/traceability-auto.md and exits 1
if a decision with consequences is cited by no spec section and is not listed in
NOT_IN_SPEC below.

Run from product/spec:  python3 tools/trace.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = sorted(p for p in (ROOT / "spec").glob("*.md") if p.name not in ("traceability-auto.md", "CHANGELOG.md"))

# decisions whose consequences are about process or documents, not about the interface
NOT_IN_SPEC = {
    "0001": "document structure",
    "0010": "scope: no compatibility modes",
    "0012": "scope: full functionality of deliverables",
    "0013": "integration route (AetherSDR); covered by the AetherSDR annex",
    "0018": "licences",
    "0019": "location of the reference model",
    "0027": "location of the test bench",
    "0033": "firmware language",
    "0034": "test process before the radio",
    "0037": "language of the management CLI",
}


def consequences(text):
    m = re.search(r"## Consequences\n(.*?)(\n## |\Z)", text, re.S)
    return len(re.findall(r"^- ", m.group(1), re.M)) if m else 0


def main():
    cites = {}
    for path in SPEC:
        heading = "(top)"
        for line in path.read_text().splitlines():
            h = re.match(r"#{2,4} (.+)", line)
            if h:
                heading = h.group(1).strip()
                continue
            for d in set(re.findall(r"(?<![\d.x])(00[0-9]{2})(?![\d.x])", line)):
                cites.setdefault(d, set()).add(f"{path.stem}: {heading}")
    rows, missing = [], []
    for p in sorted((ROOT / "decisions").glob("[0-9][0-9][0-9][0-9]-*.md")):
        d, title = p.name[:4], p.read_text().splitlines()[0].lstrip("# ").strip()
        n = consequences(p.read_text())
        where = sorted(cites.get(d, []))
        if not where and n and d not in NOT_IN_SPEC:
            missing.append(d)
        note = NOT_IN_SPEC.get(d, "")
        rows.append(f"| {d} | {title} | {n} | {len(where)} | {'; '.join(where[:6])}{' …' if len(where) > 6 else ''} | {note} |")
    out = ["# Traceability (generated by tools/trace.py — do not edit by hand)", "",
           "| Decision | Title | Consequences | Spec sections citing it | Sections (first 6) | Not in spec because |",
           "|---|---|---|---|---|---|", *rows, ""]
    if missing:
        out.append(f"Decisions with consequences but no spec citation: {', '.join(missing)}")
    (ROOT / "spec" / "traceability-auto.md").write_text("\n".join(out) + "\n")
    print("\n".join(out[-3:]) if missing else "every decision with consequences is cited or explained")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
